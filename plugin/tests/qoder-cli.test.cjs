'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')

test('Qoder launch explicitly marks CLI provenance; ordinary desktop hooks cannot inherit it from discovery', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'uta-qoder-cli-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const { buildLaunch } = await import(pathToFileURL(path.resolve(__dirname, '../plugins/qoder/scripts/launch-qoder-cli.mjs')).href)
  const launch = buildLaunch(['--uta-exe', process.execPath, '--uta-config-dir', directory, '--', '--cwd', directory], {})
  assert.equal(launch.env.UTA_QODER_SURFACE, 'cli')
  assert.equal(launch.env.UTA_QODER_EXE, process.execPath)
  assert.equal(launch.args[launch.args.indexOf('--config-dir') + 1], directory)
  assert.throws(() => buildLaunch(['--uta-exe', process.execPath, '--uta-config-dir', directory, '--', '--config-dir=other'], {}))
  const { reportHostSession } = await import(pathToFileURL(path.resolve(__dirname, '../plugins/qoder/src/uta-hook.mjs')).href)
  const env = { ...launch.env, UTA_USER_DATA_DIR: directory, UTA_RUNTIME_DIR: directory }
  reportHostSession({ session_id: 'cli-A', cwd: directory, permission_mode: 'acceptEdits' }, env)
  let record = JSON.parse(fs.readFileSync(path.join(directory, 'hooks/qoder-session.json'), 'utf8'))
  assert.equal(record.inputSurface, 'cli')
  assert.equal(record.hostConfigDir, directory)
  assert.equal(record.permissionMode, 'accept_edits')
  reportHostSession({ session_id: 'desktop-B', cwd: directory, permission_mode: 'default' }, { UTA_USER_DATA_DIR: directory, UTA_RUNTIME_DIR: directory })
  record = JSON.parse(fs.readFileSync(path.join(directory, 'hooks/qoder-session.json'), 'utf8'))
  assert.equal(record.inputSurface, 'unconfirmed')
  assert.equal(record.hostConfigDir, undefined)
  assert.equal(fs.readdirSync(path.join(directory, 'hooks/sessions/qoder')).length, 2)
})
