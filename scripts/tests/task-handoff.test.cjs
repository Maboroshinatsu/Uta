'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const { execFileSync, spawnSync } = require('node:child_process')

test('desktop receipt validates identity, frozen contract, scope and clean submission', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'uta-handoff-'))
  t.after(() => {
    const resolved = path.resolve(root)
    if (path.dirname(resolved) !== path.resolve(os.tmpdir()) || !path.basename(resolved).startsWith('uta-handoff-')) throw Error('Unexpected cleanup target')
    fs.rmSync(resolved, { recursive: true, force: true })
  })
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', windowsHide: true }).trim()
  const write = (file, value) => { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), value) }
  git('init', '-b', 'task/test/desktop')
  git('config', 'user.name', 'Uta test')
  git('config', 'user.email', 'uta-test@example.invalid')
  write('scripts/task-handoff.mjs', fs.readFileSync(path.resolve(__dirname, '../task-handoff.mjs')))
  write('.gitignore', '/.uta-task/\n')
  write('contract.ts', 'export const version = 1\n')
  git('add', '.')
  git('commit', '-m', 'fixture baseline')
  const base = git('rev-parse', 'HEAD')
  const assignment = { task: 'test', owner: 'test', directory: root, branch: 'task/test/desktop', base,
    contractHashes: { 'contract.ts': crypto.createHash('sha256').update('export const version = 1\n').digest('hex') },
    allowedFiles: ['result.md'], allowedDirectories: ['feature/'], requiredResults: ['result.md'], env: { UTA_PROFILE: 'test-only' } }
  const save = () => write('.uta-task/assignment.json', JSON.stringify(assignment))
  const run = command => spawnSync(process.execPath, ['scripts/task-handoff.mjs', command], { cwd: root, encoding: 'utf8', windowsHide: true })
  save()
  assert.equal(run('preflight').status, 0)
  assert.equal(run('submit').status, 1, 'empty baseline cannot be submitted')
  assignment.directory = path.dirname(root); save()
  assert.match(run('status').stderr, /directory mismatch/)
  assignment.directory = root; assignment.branch = 'wrong'; save()
  assert.match(run('preflight').stderr, /branch mismatch/)
  assignment.branch = 'task/test/desktop'; save()
  write('contract.ts', 'export const version = 2\n')
  assert.match(run('preflight').stderr, /Frozen contract changed/)
  write('contract.ts', 'export const version = 1\r\n')
  assert.equal(run('preflight').status, 0, 'line endings do not change the contract hash')
  git('checkout', '--', 'contract.ts')
  write('outside.md', 'unexpected')
  assert.match(run('preflight').stderr, /Outside task scope/)
  fs.unlinkSync(path.join(root, 'outside.md'))
  write('feature/index.ts', 'export const result = 1\n')
  assert.equal(run('checkpoint').status, 0)
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, '.uta-task/status.json'))).state, 'in-progress')
  assert.match(run('submit').stderr, /Commit task changes/)
  git('add', 'feature/index.ts'); git('commit', '-m', 'implement fixture')
  assert.match(run('submit').stderr, /Missing result/)
  write('result.md', 'Fixture only; no product acceptance claim.\n')
  git('add', 'result.md'); git('commit', '-m', 'record fixture result')
  const receipt = run('submit')
  assert.equal(receipt.status, 0, receipt.stderr)
  assert.equal(JSON.parse(receipt.stdout).state, 'submitted-awaiting-codex-review')
  assert.equal(JSON.parse(receipt.stdout).dirty, false)
  assignment.implementationDirectories = ['missing-feature/']; save()
  assert.match(run('submit').stderr, /Missing implementation changes/)
})
